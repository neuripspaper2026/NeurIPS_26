/* Configuration structure for different benchmark sizes */
typedef struct {
    const char *name;
    int num_searches;  /* Number of search iterations to perform */
} BenchmarkConfig;

/* Predefined size configurations */
static const BenchmarkConfig SIZE_CONFIGS[] = {
    {"mini",        1},      /* 1 iteration (current default) */
    {"small",       5000},     /* 50 iterations */
    {"medium",      20000},    /* 200 iterations */
    {"large",       80000},    /* 800 iterations */
    {"extra-large", 320000},   /* 3200 iterations */
};

static const int NUM_CONFIGS = sizeof(SIZE_CONFIGS) / sizeof(SIZE_CONFIGS[0]);

/* Get configuration by name */
static const BenchmarkConfig* get_config(const char *size_name) {
    int i;
    for (i = 0; i < NUM_CONFIGS; i++) {
        if (strcmp(SIZE_CONFIGS[i].name, size_name) == 0) {
            return &SIZE_CONFIGS[i];
        }
    }
    return NULL;
}

/* Print usage information */
static void print_usage(const char *prog_name) {
    int i;
    fprintf(stderr, "Usage: %s <size>\n", prog_name);
    fprintf(stderr, "Available sizes:\n");
    for (i = 0; i < NUM_CONFIGS; i++) {
        fprintf(stderr, "  %-12s : %d search iterations\n", 
                SIZE_CONFIGS[i].name, SIZE_CONFIGS[i].num_searches);
    }
}

