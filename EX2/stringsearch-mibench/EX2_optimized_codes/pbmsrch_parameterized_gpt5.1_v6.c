static size_t table[UCHAR_MAX + 1];
static size_t len;
static char *findme;
static double strsearch_kernel_time_acc = 0.0;

void reset_strsearch_kernel_time(void) { strsearch_kernel_time_acc = 0.0; }
double get_strsearch_kernel_time(void) { return strsearch_kernel_time_acc; }

void init_search(const char *string)
{
      size_t i;

      len = strlen(string);
      for (i = 0; i <= UCHAR_MAX; i++)                      /* rdg 10/93 */
            table[i] = len;
      for (i = 0; i < len; i++)
            table[(unsigned char)string[i]] = len - i - 1;
      findme = (char *)string;
}

char *strsearch(const char *string)
{
      size_t shift = 1; /* initialize to non-zero to avoid UB before first use */
      size_t pos = len - 1;
      char *here = NULL;
      char *result = NULL;
      size_t limit = strlen(string);
      struct timespec kernel_start, kernel_end;

      clock_gettime(CLOCK_MONOTONIC, &kernel_start);

      /* Main search loop: kept serial to preserve timing and avoid race
         conditions on shared globals without changing the API. */
      while (pos < limit)
      {
            /* Use a tighter inner loop with local variables to help the
               compiler optimize and reduce repeated work. */
            const unsigned char *ustr = (const unsigned char *)string;
            const size_t *restrict t = table;
            const size_t local_len = len;

            while (pos < limit &&
                   (shift = t[ustr[pos]]) != 0)
            {
                  pos += shift;
            }

            if (shift == 0)
            {
                  here = (char *)&string[pos - local_len + 1];
                  if (0 == strncmp(findme, here, local_len))
                  {
                        result = here;
                        break;
                  }
                  /* Advance at least one character to avoid re-checking
                     the same position. */
                  ++pos;
            }
      }

      clock_gettime(CLOCK_MONOTONIC, &kernel_end);
      strsearch_kernel_time_acc += (kernel_end.tv_sec - kernel_start.tv_sec) +
                                   (kernel_end.tv_nsec - kernel_start.tv_nsec) / 1e9;
      return result;
}

